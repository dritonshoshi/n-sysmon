package com.nsysmon.measure.jdbc;

import com.nsysmon.NSysMonApi;
import com.nsysmon.data.AHierarchicalData;
import com.nsysmon.testutil.CollectingDataSink;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class NSysMonStatementTest {

    @Mock private Connection wrappedConnection;
    @Mock private Statement innerStatement;

    private CollectingDataSink dataSink;
    private NSysMonApi sysMon;
    private Connection rawConnection;
    private NSysMonStatement realStmt;
    private NSysMonStatement mockStmt;

    @BeforeEach void before() throws SQLException {
        dataSink = new CollectingDataSink();
        sysMon = JdbcTestSupport.createSysMon(dataSink);
        mockStmt = new NSysMonStatement(wrappedConnection, innerStatement, sysMon);

        rawConnection = JdbcTestSupport.createDataSource().getConnection();
        try (Statement setup = rawConnection.createStatement()) {
            setup.execute("create table T (id int, name varchar(20))");
            setup.execute("insert into T values (1, 'one')");
        }
        realStmt = new NSysMonStatement(wrappedConnection, rawConnection.createStatement(), sysMon);
    }

    @AfterEach void after() throws SQLException {
        rawConnection.close();
    }

    @Test void ident_prefixesTheStatementWithJdbc() {
        assertEquals("jdbc: select 1", NSysMonStatement.ident("select 1"));
        assertEquals("jdbc:", NSysMonStatement.IDENT_PREFIX_JDBC);
        assertEquals("execute", NSysMonStatement.IDENT_EXECUTE);
    }

    @Test void executeQuery_recordsTheSqlAndTheExecuteDetail() throws SQLException {
        inOuterMeasurement(() -> {
            try (ResultSet rs = realStmt.executeQuery("select id from T")) {
                assertInstanceOf(NSysMonResultSet.class, rs);
                assertSame(realStmt, rs.getStatement());
            }
        });

        final AHierarchicalData query = rootChildren().get(0);
        assertEquals("jdbc: select id from T", query.getIdentifier());
        assertEquals(List.of("execute"), identifiers(query));
    }

    @Test void iteratingTheResultSetIsRecordedAsADetail() throws SQLException {
        inOuterMeasurement(() -> {
            try (ResultSet rs = realStmt.executeQuery("select id from T")) {
                while (rs.next()) {
                    assertEquals(1, rs.getInt(1));
                }
            }
        });

        assertEquals(List.of("execute", "result set access"), identifiers(rootChildren().get(0)));
    }

    @Test void executeQuery_propagatesSqlErrors() {
        assertThrows(SQLException.class, () -> realStmt.executeQuery("select from where"));

        assertTrue(dataSink.data.isEmpty());
    }

    @Test void executeUpdate_recordsTheNumberOfAffectedRows() throws SQLException {
        assertEquals(1, realStmt.executeUpdate("insert into T values (2, 'two')"));

        assertEquals("jdbc: insert into T values (2, 'two')", onlyRoot().getIdentifier());
    }

    @Test void execute_recordsWhetherTheStatementReturnedAResultSet() throws SQLException {
        assertTrue(realStmt.execute("select id from T"));

        assertEquals("jdbc: select id from T", onlyRoot().getIdentifier());
    }

    @Test void executeUpdateWithAutoGeneratedKeys_isDelegated() throws SQLException {
        assertEquals(1, realStmt.executeUpdate("insert into T values (3, 'three')", Statement.RETURN_GENERATED_KEYS));

        assertEquals("jdbc: insert into T values (3, 'three')", onlyRoot().getIdentifier());
    }

    @Test void executeUpdateWithColumnIndexes_isDelegated() throws SQLException {
        assertEquals(1, realStmt.executeUpdate("insert into T values (4, 'four')", new int[]{1}));

        assertEquals("jdbc: insert into T values (4, 'four')", onlyRoot().getIdentifier());
    }

    @Test void executeUpdateWithColumnNames_isDelegated() throws SQLException {
        assertEquals(1, realStmt.executeUpdate("insert into T values (5, 'five')", new String[]{"id"}));

        assertEquals("jdbc: insert into T values (5, 'five')", onlyRoot().getIdentifier());
    }

    @Test void executeWithAutoGeneratedKeys_isDelegated() throws SQLException {
        realStmt.execute("insert into T values (6, 'six')", Statement.RETURN_GENERATED_KEYS);

        assertEquals("jdbc: insert into T values (6, 'six')", onlyRoot().getIdentifier());
    }

    @Test void executeWithColumnIndexes_isDelegated() throws SQLException {
        realStmt.execute("insert into T values (7, 'seven')", new int[]{1});

        assertEquals("jdbc: insert into T values (7, 'seven')", onlyRoot().getIdentifier());
    }

    @Test void executeWithColumnNames_isDelegated() throws SQLException {
        realStmt.execute("insert into T values (8, 'eight')", new String[]{"id"});

        assertEquals("jdbc: insert into T values (8, 'eight')", onlyRoot().getIdentifier());
    }

    @Test void executingAStatementStartsExactlyOneMeasurement() throws SQLException {
        realStmt.execute("select id from T");

        assertEquals(1, dataSink.numStarted);
        assertEquals(1, dataSink.data.size());
    }

    @Test void getConnection_returnsTheConnectionTheStatementWasCreatedFrom() throws SQLException {
        assertSame(wrappedConnection, mockStmt.getConnection());
    }

    @Test void unwrapAndIsWrapperForAreDelegated() throws SQLException {
        when(innerStatement.unwrap(Statement.class)).thenReturn(innerStatement);
        when(innerStatement.isWrapperFor(Statement.class)).thenReturn(true);

        assertSame(innerStatement, mockStmt.unwrap(Statement.class));
        assertTrue(mockStmt.isWrapperFor(Statement.class));
    }

    @Test void batchMethodsAreDelegated() throws SQLException {
        when(innerStatement.executeBatch()).thenReturn(new int[]{1, 1});

        mockStmt.addBatch("insert into T values (1, 'a')");
        mockStmt.addBatch("insert into T values (2, 'b')");

        assertEquals(2, mockStmt.executeBatch().length);
        mockStmt.clearBatch();

        verify(innerStatement).addBatch("insert into T values (1, 'a')");
        verify(innerStatement).addBatch("insert into T values (2, 'b')");
        verify(innerStatement).clearBatch();
    }

    @Test void resultSetStateMethodsAreDelegated() throws SQLException {
        final ResultSet resultSet = org.mockito.Mockito.mock(ResultSet.class);
        when(innerStatement.getResultSet()).thenReturn(resultSet);
        when(innerStatement.getUpdateCount()).thenReturn(-1);
        when(innerStatement.getMoreResults()).thenReturn(true);
        when(innerStatement.getMoreResults(Statement.KEEP_CURRENT_RESULT)).thenReturn(false);
        final ResultSet generatedKeys = org.mockito.Mockito.mock(ResultSet.class);
        when(innerStatement.getGeneratedKeys()).thenReturn(generatedKeys);

        assertSame(generatedKeys, mockStmt.getGeneratedKeys());
        assertSame(resultSet, mockStmt.getResultSet());
        assertEquals(-1, mockStmt.getUpdateCount());
        assertTrue(mockStmt.getMoreResults());
        assertFalse(mockStmt.getMoreResults(Statement.KEEP_CURRENT_RESULT));
    }

    @Test void fetchSizeAndDirectionAreDelegated() throws SQLException {
        when(innerStatement.getFetchSize()).thenReturn(42);
        when(innerStatement.getFetchDirection()).thenReturn(ResultSet.FETCH_FORWARD);

        mockStmt.setFetchSize(42);
        mockStmt.setFetchDirection(ResultSet.FETCH_FORWARD);

        assertEquals(42, mockStmt.getFetchSize());
        assertEquals(ResultSet.FETCH_FORWARD, mockStmt.getFetchDirection());
    }

    @Test void maxRowsAndFieldSizeAreDelegated() throws SQLException {
        when(innerStatement.getMaxRows()).thenReturn(10);
        when(innerStatement.getMaxFieldSize()).thenReturn(1024);

        mockStmt.setMaxRows(10);
        mockStmt.setMaxFieldSize(1024);

        assertEquals(10, mockStmt.getMaxRows());
        assertEquals(1024, mockStmt.getMaxFieldSize());
    }

    @Test void queryTimeoutAndEscapeProcessingAreDelegated() throws SQLException {
        when(innerStatement.getQueryTimeout()).thenReturn(7);

        mockStmt.setQueryTimeout(7);
        mockStmt.setEscapeProcessing(false);
        mockStmt.cancel();

        assertEquals(7, mockStmt.getQueryTimeout());
        verify(innerStatement).setQueryTimeout(7);
        verify(innerStatement).setEscapeProcessing(false);
        verify(innerStatement).cancel();
    }

    @Test void warningsAndCursorNameAreDelegated() throws SQLException {
        final SQLWarning warning = new SQLWarning("careful");
        when(innerStatement.getWarnings()).thenReturn(warning);

        assertSame(warning, mockStmt.getWarnings());
        mockStmt.clearWarnings();
        mockStmt.setCursorName("cursor");

        verify(innerStatement).clearWarnings();
        verify(innerStatement).setCursorName("cursor");
    }

    @Test void resultSetPropertiesAreDelegated() throws SQLException {
        when(innerStatement.getResultSetType()).thenReturn(ResultSet.TYPE_FORWARD_ONLY);
        when(innerStatement.getResultSetConcurrency()).thenReturn(ResultSet.CONCUR_UPDATABLE);
        when(innerStatement.getResultSetHoldability()).thenReturn(ResultSet.HOLD_CURSORS_OVER_COMMIT);

        assertEquals(ResultSet.TYPE_FORWARD_ONLY, mockStmt.getResultSetType());
        assertEquals(ResultSet.CONCUR_UPDATABLE, mockStmt.getResultSetConcurrency());
        assertEquals(ResultSet.HOLD_CURSORS_OVER_COMMIT, mockStmt.getResultSetHoldability());
    }

    @Test void poolabilityAndCloseOnCompletionAreDelegated() throws SQLException {
        when(innerStatement.isPoolable()).thenReturn(true);
        when(innerStatement.isCloseOnCompletion()).thenReturn(true);

        mockStmt.setPoolable(true);
        mockStmt.closeOnCompletion();

        assertTrue(mockStmt.isPoolable());
        assertTrue(mockStmt.isCloseOnCompletion());
        verify(innerStatement).setPoolable(true);
        verify(innerStatement).closeOnCompletion();
    }

    @Test void closeAndIsClosedAreDelegated() throws SQLException {
        when(innerStatement.isClosed()).thenReturn(true);

        mockStmt.close();

        assertTrue(mockStmt.isClosed());
        verify(innerStatement).close();
    }

    private void inOuterMeasurement(SqlRunnable runnable) throws SQLException {
        sysMon.measure("outer", m -> {
            runnable.run();
            return null;
        });
    }

    @FunctionalInterface
    private interface SqlRunnable {
        void run() throws SQLException;
    }

    private AHierarchicalData onlyRoot() {
        assertEquals(1, dataSink.data.size());
        return dataSink.data.get(0).getRootNode();
    }

    private List<AHierarchicalData> rootChildren() {
        final AHierarchicalData root = onlyRoot();
        assertEquals("outer", root.getIdentifier());
        return root.getChildren();
    }

    private List<String> identifiers(AHierarchicalData data) {
        final List<String> result = new ArrayList<>();
        data.getChildren().forEach(child -> result.add(child.getIdentifier()));
        return result;
    }
}
